    class SortFilter : AnimeFilter.Select<String>("Sort by", SORTS.map { it.name }.toTypedArray())

    class GenreTriState(name: String, val value: String) : AnimeFilter.TriState(name)

    class GenreFilter : AnimeFilter.Group<GenreTriState>("Genres (tap twice to exclude)", GENRES.map { GenreTriState(it.first, it.second) })

    class StudioFilter : AnimeFilter.Select<String>("Studio", (listOf("Any") + BRANDS).toTypedArray())

    class Params(
        val sort: SortOption,
        val isDefaultSort: Boolean,
        val include: List<String>,
        val exclude: List<String>,
        val studio: String?,
    ) {
        /** True when only the API's genre/studio browsing can answer the request. */
        val needsBrowse: Boolean get() = include.isNotEmpty() || exclude.isNotEmpty() || studio != null
    }

    fun getFilterList() = AnimeFilterList(
        AnimeFilter.Header("A text search returns up to 100 matches; filters narrow them down"),
        SortFilter(),
        StudioFilter(),
        GenreFilter(),
    )

    fun parse(filters: AnimeFilterList): Params {
        var sortIndex = 0
        var studio: String? = null
        val include = mutableListOf<String>()
        val exclude = mutableListOf<String>()
        filters.forEach { filter ->
            when (filter) {
                is SortFilter -> sortIndex = filter.state
                is StudioFilter -> studio = if (filter.state > 0) BRANDS.getOrNull(filter.state - 1) else null
                is GenreFilter -> filter.state.forEach { genre ->
                    when {
                        genre.isIncluded() -> include += genre.value
                        genre.isExcluded() -> exclude += genre.value
                    }
                }
                else -> {}
            }
        }
        return Params(SORTS.getOrElse(sortIndex) { SORTS[0] }, sortIndex == 0, include, exclude, studio)
    }

